-- Soft Delete Trigger for inventorylist
CREATE OR REPLACE FUNCTION log_soft_delete_inventory()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO audit_log (TABLE_NAME, OPERATION, OLD_DATA, TIMESTAMP)
  VALUES ('inventorylist', 'SOFT_DELETE', row_to_json(OLD), CURRENT_TIMESTAMP);
  RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_soft_delete_inventory
AFTER UPDATE OF DELETED ON inventorylist
FOR EACH ROW
WHEN (NEW.DELETED = true)
EXECUTE FUNCTION log_soft_delete_inventory();


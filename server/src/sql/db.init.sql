-- General Change Logging Trigger
CREATE OR REPLACE FUNCTION log_changes_inventory()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO audit_log (TABLE_NAME, OPERATION, OLD_DATA, NEW_DATA, TIMESTAMP)
  VALUES ('inventorylist', TG_OP, row_to_json(OLD), row_to_json(NEW), CURRENT_TIMESTAMP);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_log_changes_inventory
AFTER INSERT OR UPDATE OR DELETE ON inventorylist
FOR EACH ROW
EXECUTE FUNCTION log_changes_inventory();
